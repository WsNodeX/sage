import unittest

from sage.registry import Prompt, Resource, Tool, prompt, resource, tool


def adder(a: int, b: int) -> int:
    """Add two numbers.

    :param a: left
    :param b: right
    """
    return a + b


def doc_reader() -> str:
    return "hello"


def greeter(name: str) -> str:
    return "hi %s" % name


class TestDecorators(unittest.TestCase):
    def test_standalone_tool(self):
        t = tool(name="add", description="add")(adder)
        self.assertIsInstance(t, Tool)
        self.assertEqual(t.name, "add")
        self.assertEqual(t.invoke({"a": 2, "b": 3}), 5)

    def test_tool_schema_autogenerated(self):
        t = tool()(adder)
        schema = t.input_schema
        self.assertEqual(set(schema["required"]), {"a", "b"})
        self.assertEqual(schema["properties"]["a"]["type"], "integer")

    def test_resource_uri(self):
        r = resource(uri="mem://x", description="d")(doc_reader)
        self.assertIsInstance(r, Resource)
        self.assertEqual(r.uri, "mem://x")
        self.assertEqual(r.read(), "hello")

    def test_prompt_arguments_inferred(self):
        p = prompt()(greeter)
        self.assertIsInstance(p, Prompt)
        self.assertEqual(p.arguments[0]["name"], "name")
        messages = p.render({"name": "Sam"})
        self.assertEqual(messages[0]["role"], "user")
        self.assertIn("Sam", messages[0]["content"]["text"])


class TestDescribe(unittest.TestCase):
    def test_tool_describe(self):
        t = Tool("add", "add two", adder)
        d = t.describe()
        self.assertEqual(d["name"], "add")
        self.assertIn("inputSchema", d)

    def test_resource_describe(self):
        r = Resource("u", "n", "d", doc_reader, "text/plain")
        d = r.describe()
        self.assertEqual(d["mimeType"], "text/plain")

    def test_prompt_describe(self):
        p = Prompt("g", "greet", greeter)
        d = p.describe()
        self.assertEqual(d["name"], "g")
        self.assertEqual(d["arguments"][0]["name"], "name")


if __name__ == "__main__":
    unittest.main()
